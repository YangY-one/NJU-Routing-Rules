#!/usr/bin/env python3
"""Passively discover NJU hostnames and compare web reachability from two networks."""

import argparse
import csv
import json
import re
import ssl
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path


FIELDS = ("host", "result", "detail")


def valid_host(value):
    host = value.strip().lower().rstrip(".")
    labels = host.split(".")
    if len(labels) != 4 or labels[1:] != ["nju", "edu", "cn"]:
        return None
    alphabet = "abcdefghijklmnopqrstuvwxyz0123456789"
    if not all(label and len(label) <= 63 and label[0] in alphabet
               and label[-1] in alphabet and all(c in alphabet + "-" for c in label)
               for label in labels):
        return None
    return host


def read_hosts(path):
    hosts = set()
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            host = valid_host(line)
            if not host:
                raise ValueError(f"invalid four-label NJU hostname: {line}")
            hosts.add(host)
    return sorted(hosts)


def write_lines(path, lines):
    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")


def discover(args):
    # CT is passive and incomplete: private certificates and DNS-only hosts are absent.
    url = "https://crt.sh/?q=%25.nju.edu.cn&output=json"
    request = urllib.request.Request(url, headers={"User-Agent": "nju-domain-check/1.0"})
    with urllib.request.urlopen(request, timeout=args.timeout) as response:
        data = response.read(25_000_001)
    if len(data) > 25_000_000:
        raise ValueError("CT response exceeds 25 MB; use --hosts with a saved list")
    hosts = set(read_hosts(args.seed)) if args.seed else set()
    for entry in json.loads(data):
        for name in entry.get("name_value", "").splitlines():
            host = valid_host(name)
            if host:
                hosts.add(host)
    write_lines(args.out, sorted(hosts))
    print(f"Discovered {len(hosts)} hosts in {args.out}")


def request_page(host, scheme, timeout, proxy):
    if proxy == "direct":
        handler = urllib.request.ProxyHandler({})
    elif proxy == "system":
        handler = urllib.request.ProxyHandler()
    else:
        handler = urllib.request.ProxyHandler({"http": proxy, "https": proxy})
    opener = urllib.request.build_opener(handler)
    request = urllib.request.Request(f"{scheme}://{host}/",
                                     headers={"User-Agent": "nju-domain-check/1.0"})
    try:
        with opener.open(request, timeout=timeout) as response:
            return page_result(response.read(65536), response.headers.get_content_charset(),
                               scheme, response.status)
    except urllib.error.HTTPError as error:
        # Gateway failures can be generated by a proxy.
        if proxy != "direct" and error.code in {407, 502, 503, 504}:
            return "proxy_error", f"{scheme}:{error.code}"
        return page_result(error.read(65536), error.headers.get_content_charset(),
                           scheme, error.code)


def page_result(body, charset, scheme, status):
    try:
        content = body.decode(charset or "utf-8", errors="replace")
    except LookupError:
        content = body.decode("utf-8", errors="replace")
    title = re.search(r"<title[^>]*>(.*?)</title>", content, re.I | re.S)
    if (title and "温馨提示" in title.group(1)) or any(
            phrase in content for phrase in
            ("仅允许校内", "只允许校内", "仅限校内", "并非校内", "校外无法访问")):
        return "notice", f"{scheme}:{status}"
    if status in {401, 403} or status >= 500:
        return "http_error", f"{scheme}:{status}"
    return "reachable", f"{scheme}:{status}"


def probe_one(host, timeout, proxy):
    failures = []
    tls_error = False
    for scheme in ("https", "http"):
        try:
            result, detail = request_page(host, scheme, timeout, proxy)
            return host, result, detail
        except urllib.error.URLError as error:
            reason = error.reason
            if isinstance(reason, ssl.SSLError):
                tls_error = True
            failures.append(f"{scheme}:{type(reason).__name__}")
        except (OSError, TimeoutError) as error:
            failures.append(f"{scheme}:{type(error).__name__}")
    return host, "tls_error" if tls_error else "unreachable", ";".join(failures)


def probe(args):
    hosts = read_hosts(args.hosts)
    if args.limit:
        hosts = hosts[:args.limit]
    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        results = [future.result() for future in as_completed(
            pool.submit(probe_one, host, args.timeout, args.proxy) for host in hosts)]
    output_path = Path(args.out)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="utf-8", newline="") as output:
        writer = csv.writer(output)
        writer.writerow(FIELDS)
        writer.writerows(sorted(results))
    if args.problem_out:
        write_lines(args.problem_out,
                    sorted(host for host, result, _ in results
                           if result in {"unreachable", "notice", "tls_error", "http_error", "proxy_error"}))
    counts = {result: sum(row[1] == result for row in results)
              for result in sorted({row[1] for row in results})}
    print(f"Probed {len(results)} hosts into {args.out}: {counts}")


def read_results(path):
    with Path(path).open(encoding="utf-8", newline="") as source:
        reader = csv.DictReader(source)
        if not set(FIELDS).issubset(reader.fieldnames or []):
            raise ValueError(f"missing CSV columns in {path}")
        return {row["host"]: row["result"] for row in reader}


def select(args):
    confirmed = set(read_hosts(args.confirmed)) if args.confirmed else set()
    if args.external and args.internal:
        external, internal = read_results(args.external), read_results(args.internal)
        confirmed.update(host for host in external.keys() & internal.keys()
                         if external[host] in {"unreachable", "notice", "tls_error", "http_error"}
                         and internal[host] == "reachable")
    elif args.external or args.internal:
        raise ValueError("provide both --external and --internal")
    write_lines(args.out, sorted(confirmed))
    print(f"Selected {len(confirmed)} domain hosts into {args.out}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    discovery = commands.add_parser("discover", help="collect four-label hosts from CT")
    discovery.add_argument("--out", default="nju-hosts.txt")
    discovery.add_argument("--seed", help="optional additional host list")
    discovery.add_argument("--timeout", type=float, default=20)
    discovery.set_defaults(func=discover)
    check = commands.add_parser("probe", help="run from outside, then campus/VPN")
    check.add_argument("--hosts", required=True)
    check.add_argument("--out", required=True)
    check.add_argument("--problem-out", help="plain-text list of hosts with non-reachable results")
    check.add_argument("--proxy", default="system",
                       help="system (default), direct, or HTTP proxy URL")
    check.add_argument("--workers", type=int, default=3)
    check.add_argument("--timeout", type=float, default=4)
    check.add_argument("--limit", type=int, default=0)
    check.set_defaults(func=probe)
    output = commands.add_parser("select", help="select hosts from two probe results")
    output.add_argument("--external")
    output.add_argument("--internal")
    output.add_argument("--confirmed", help="hosts already confirmed by hand")
    output.add_argument("--out", default="sources/domains.txt")
    output.set_defaults(func=select)
    args = parser.parse_args()
    if hasattr(args, "workers") and not 1 <= args.workers <= 10:
        parser.error("--workers must be between 1 and 10")
    if hasattr(args, "timeout") and args.timeout <= 0:
        parser.error("--timeout must be positive")
    try:
        args.func(args)
    except (OSError, ValueError, json.JSONDecodeError) as error:
        parser.exit(1, f"error: {error}\n")


if __name__ == "__main__":
    main()
